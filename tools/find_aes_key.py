def is_likely_string(blob: bytes) -> bool:
    """True if this looks like (part of) an ASCII string or UTF-16 string."""
    # ASCII-mostly (printable + nul terminators)
    printable_or_null = sum(1 for b in blob if (0x20 <= b <= 0x7e) or b == 0)
    if printable_or_null >= 12:
        return True
    # UTF-16LE pattern: every odd byte is \x00 and even bytes are ASCII
    if all(blob[i + 1] == 0 and (0x20 <= blob[i] <= 0x7e or blob[i] == 0) for i in range(0, 16, 2)):
        return True
    return False


def is_low_entropy(blob: bytes) -> bool:
    """Heuristic: lots of repeats, runs, or simple patterns."""
    unique = len(set(blob))
    if unique < 10:
        return True
    # Long run of same byte
    for i in range(len(blob) - 3):
        if blob[i] == blob[i + 1] == blob[i + 2] == blob[i + 3]:
            return True
    return False


def main() -> None:
    pe_path = Path(sys.argv[1])
    data = pe_path.read_bytes()
    pe = pefile.PE(str(pe_path), fast_load=False)

    sbox_off = data.find(AES_SBOX)
    print(f"AES S-box at file offset 0x{sbox_off:08x}")

    # Locate .rdata
    rdata_section = None
    for section in pe.sections:
        if section.Name.rstrip(b"\x00") == b".rdata":
            rdata_section = section
            break
    assert rdata_section is not None
    rstart = rdata_section.PointerToRawData
    rend = rstart + rdata_section.SizeOfRawData
    print(f".rdata: 0x{rstart:08x}..0x{rend:08x}  ({rend - rstart:,} bytes)")

    # Window: ±8 KB around AES S-box
    win_start = max(rstart, sbox_off - 8192)
    win_end = min(rend, sbox_off + len(AES_SBOX) + 8192)
    print(f"\n--- Scanning window 0x{win_start:08x}..0x{win_end:08x} ({win_end - win_start:,} bytes) ---")
    print("(skipping ASCII/UTF-16 strings, low-entropy patterns, runs of repeated bytes)\n")

    candidates = []
    for off in range(win_start, win_end - 16):
        blob = data[off:off + 16]
        if blob == b"\x00" * 16:
            continue
        if is_likely_string(blob):
            continue
        if is_low_entropy(blob):
            continue
        # Don't dump anything inside the S-box or inverse-S-box itself
        if sbox_off <= off < sbox_off + 256:
            continue
        candidates.append((off, blob))

    # Group consecutive matches (sliding window finds many overlapping)
    # Group by clustering: if next offset is within 16 of previous, skip
    print(f"Raw candidates: {len(candidates)}")
    clustered = []
    last_off = -100
    for off, blob in candidates:
        if off - last_off >= 16:
            clustered.append((off, blob))
            last_off = off

    print(f"After clustering (every 16+ bytes): {len(clustered)}\n")
    print("Top 80:")
    for off, blob in clustered[:80]:
        rel = off - sbox_off
        sign = "+" if rel >= 0 else "-"
        print(f"  0x{off:08x}  ({sign}{abs(rel):#06x} from S-box)  {blob.hex()}")


if __name__ == "__main__":
    main()
